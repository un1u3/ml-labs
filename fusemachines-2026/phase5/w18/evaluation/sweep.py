"""Threshold sweep for the two tunable guardrails (safety vs usability).

    python -m evaluation.sweep
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.knowledge_base import KnowledgeBase  # noqa: E402
from evaluation.run_eval import metrics, run_case  # noqa: E402
from evaluation.test_cases import CASES  # noqa: E402
from guardrails import groundedness, injection  # noqa: E402


def sweep(module, attr, values, guardrail, kb):
    original = getattr(module, attr)
    rows = []
    for v in values:
        setattr(module, attr, v)
        m = metrics([run_case(c, kb) for c in CASES])[guardrail]
        rows.append((v, m["tp"], m["fp"], m["fn"], m["false_positive_ids"], m["false_negative_ids"]))
    setattr(module, attr, original)
    return rows


def main():
    kb = KnowledgeBase()
    lines = ["# Threshold sweeps\n", "Generated by `python -m evaluation.sweep` over the labelled suite.\n"]
    for title, module, attr, values, g in [
        ("Groundedness: lexical support threshold (current 0.6)", groundedness, "SUPPORT_THRESHOLD",
         [0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9], "groundedness"),
        ("Prompt injection: block threshold (current 0.5)", injection, "BLOCK_THRESHOLD",
         [0.25, 0.3, 0.4, 0.5, 0.6, 0.7, 0.8], "injection"),
    ]:
        lines += [f"## {title}\n", "| Threshold | TP | FP | FN | False positives | False negatives |", "|---|---|---|---|---|---|"]
        for v, tp, fp, fn, fps, fns in sweep(module, attr, values, g, kb):
            lines.append(f"| {v} | {tp} | {fp} | {fn} | {', '.join(fps) or '-'} | {', '.join(fns) or '-'} |")
        lines.append("")
    out = Path(__file__).resolve().parent.parent / "reports" / "threshold_sweep.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
