"""Run the labelled evaluation suite and write reports/eval_results.{json,md}.

    python -m evaluation.run_eval
"""
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.knowledge_base import KnowledgeBase  # noqa: E402
from app.llm import MockLLM, ScriptedLLM  # noqa: E402
from app.pipeline import GuardedAssistant  # noqa: E402
from evaluation.test_cases import CASES  # noqa: E402

BINARY_GUARDRAILS = ["pii_input", "injection", "sensitive_topic", "schema", "groundedness", "output_sensitive"]


def run_case(case: Dict[str, Any], kb: KnowledgeBase) -> Dict[str, Any]:
    llm = ScriptedLLM(case["llm_outputs"]) if case.get("llm_outputs") else MockLLM()
    r = GuardedAssistant(llm=llm, kb=kb).handle(case["input"])
    exp = case["expect"]
    topic = next((t["details"].get("category") for t in r.trace if t["name"] == "sensitive_topic" and t["flagged"]), None)
    actual = {"status": r.status, "sensitive_topic": topic}
    for g in BINARY_GUARDRAILS:
        if g != "sensitive_topic":
            actual[g] = r.flagged(g)

    problems: List[str] = []
    if r.status != exp["status"]:
        problems.append(f"status {r.status} != {exp['status']}")
    for g in BINARY_GUARDRAILS:
        if g in exp and exp[g] != actual[g]:
            problems.append(f"{g}: expected {exp[g]}, got {actual[g]}")
    chk = case.get("checks", {})
    for s in chk.get("answer_contains", []):
        if s not in r.answer:
            problems.append(f"answer missing '{s}'")
    for s in chk.get("answer_excludes", []):
        if s in r.answer:
            problems.append(f"answer contains '{s}'")
    for s in chk.get("llm_input_excludes", []):
        if r.llm_input and s in r.llm_input:
            problems.append(f"model input contains '{s}'")
    if "llm_called" in chk and (r.llm_input is not None) != chk["llm_called"]:
        problems.append(f"llm_called expected {chk['llm_called']}")
    if "needs_human" in chk and r.needs_human != chk["needs_human"]:
        problems.append(f"needs_human expected {chk['needs_human']}")
    if "attempts" in chk and r.attempts != chk["attempts"]:
        problems.append(f"attempts {r.attempts} != {chk['attempts']}")

    return {
        "id": case["id"], "group": case["group"], "note": case.get("note", ""),
        "input": case["input"], "scripted_outputs": case.get("llm_outputs"),
        "reference_docs": r.retrieved, "expected": exp, "actual": actual,
        "answer": r.answer, "attempts": r.attempts,
        "flag_reasons": [f"{t['name']}: {t['reason']}" for t in r.trace if t["flagged"]],
        "passed": not problems, "problems": problems,
    }


def metrics(results: List[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    out = {}
    for g in BINARY_GUARDRAILS:
        tp = fp = fn = tn = 0
        fps, fns = [], []
        for r in results:
            if g not in r["expected"]:
                continue
            e = bool(r["expected"][g])
            a = bool(r["actual"][g])
            if g == "sensitive_topic" and e and a and r["expected"][g] != r["actual"][g]:
                # flagged, but wrong category: count as both a miss and a false alarm
                fp += 1; fn += 1; fps.append(r["id"]); fns.append(r["id"])
                continue
            if e and a: tp += 1
            elif a: fp += 1; fps.append(r["id"])
            elif e: fn += 1; fns.append(r["id"])
            else: tn += 1
        n = tp + fp + fn + tn
        p = tp / (tp + fp) if tp + fp else None
        rec = tp / (tp + fn) if tp + fn else None
        f1 = 2 * p * rec / (p + rec) if p and rec else None
        out[g] = dict(n=n, tp=tp, fp=fp, fn=fn, tn=tn, precision=p, recall=rec, f1=f1,
                      accuracy=(tp + tn) / n if n else None, false_positive_ids=fps, false_negative_ids=fns)
    return out


def _f(x):
    return "n/a" if x is None else f"{x:.2f}"


def _short(s: str, n: int = 90) -> str:
    s = s.replace("\n", " ").replace("|", "\\|").replace("\u200b", "<ZWSP>")
    return s if len(s) <= n else s[: n - 1] + "…"


def _labels(d: Dict[str, Any]) -> str:
    parts = [f"status={d['status']}"]
    for g in BINARY_GUARDRAILS:
        if g in d and d[g]:
            parts.append(g if d[g] is True else f"{g}={d[g]}")
    return ", ".join(parts)


def write_markdown(results, m, path: Path) -> None:
    passed = sum(r["passed"] for r in results)
    L = [f"# Evaluation results\n",
         f"**{passed}/{len(results)} test cases passed** ({passed / len(results):.0%}).\n",
         "Generated by `python -m evaluation.run_eval`. Labels list only the guardrails expected to fire; "
         "every guardrail named in a case's `expect` is scored, including those expected *not* to fire.\n",
         "## Metrics per guardrail\n",
         "| Guardrail | Cases scored | TP | FP | FN | TN | Precision | Recall | F1 | Accuracy | False positives | False negatives |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for g, s in m.items():
        L.append(f"| {g} | {s['n']} | {s['tp']} | {s['fp']} | {s['fn']} | {s['tn']} | {_f(s['precision'])} | {_f(s['recall'])} | "
                 f"{_f(s['f1'])} | {_f(s['accuracy'])} | {', '.join(s['false_positive_ids']) or '-'} | {', '.join(s['false_negative_ids']) or '-'} |")
    groups = {}
    for r in results:
        groups.setdefault(r["group"], []).append(r["passed"])
    L += ["\n## Pass rate by group\n", "| Group | Passed | Total |", "|---|---|---|"]
    for gname, v in groups.items():
        L.append(f"| {gname} | {sum(v)} | {len(v)} |")
    L += ["\n## Test cases\n",
          "| ID | Group | Input | Reference docs | Expected | Actual | Result |",
          "|---|---|---|---|---|---|---|"]
    for r in results:
        inp = _short(r["input"])
        if r["scripted_outputs"]:
            inp += f"<br>*scripted model output:* `{_short(r['scripted_outputs'][0], 110)}`"
            if len(r["scripted_outputs"]) > 1:
                inp += " (then a corrected output)"
        if r["note"]:
            inp += f"<br>*{r['note']}*"
        L.append(f"| {r['id']} | {r['group']} | {inp} | {', '.join(r['reference_docs']) or '-'} | {_labels(r['expected'])} | "
                 f"{_labels(r['actual'])} | {'PASS' if r['passed'] else 'FAIL: ' + '; '.join(r['problems'])} |")
    L += ["\n## Final answers and flag reasons\n"]
    for r in results:
        L.append(f"**{r['id']}** ({'PASS' if r['passed'] else 'FAIL'}, attempts={r['attempts']}): {_short(r['answer'], 300)}  ")
        for fr in r["flag_reasons"]:
            L.append(f"  - {_short(fr, 200)}")
        L.append("")
    path.write_text("\n".join(L), encoding="utf-8")


def main() -> int:
    kb = KnowledgeBase()
    results = [run_case(c, kb) for c in CASES]
    m = metrics(results)
    reports = ROOT / "reports"
    reports.mkdir(exist_ok=True)
    (reports / "eval_results.json").write_text(json.dumps({"metrics": m, "results": results}, indent=2), encoding="utf-8")
    write_markdown(results, m, reports / "eval_results.md")

    passed = sum(r["passed"] for r in results)
    print(f"{passed}/{len(results)} cases passed\n")
    print(f"{'guardrail':<17}{'n':>4}{'TP':>4}{'FP':>4}{'FN':>4}{'TN':>4}  precision  recall")
    for g, s in m.items():
        print(f"{g:<17}{s['n']:>4}{s['tp']:>4}{s['fp']:>4}{s['fn']:>4}{s['tn']:>4}  {_f(s['precision']):>9}  {_f(s['recall']):>6}")
    fails = [r for r in results if not r["passed"]]
    if fails:
        print("\nFailed cases:")
        for r in fails:
            print(f"  {r['id']}: {'; '.join(r['problems'])}")
    print(f"\nWrote {reports / 'eval_results.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
