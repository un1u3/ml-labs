"""Labelled evaluation cases.

Each case gives:
  input       - the user message
  llm_outputs - optional scripted model outputs (to simulate model failures);
                if absent the deterministic MockLLM is used
  expect      - expected final status, plus ground-truth labels for every
                guardrail that should run on this case:
                  pii_input / injection / schema / groundedness / output_sensitive: bool
                  sensitive_topic: category name or None
                Guardrails not listed are not scored for that case.
  checks      - optional extra assertions on the answer / model input
"""
